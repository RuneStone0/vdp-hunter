@app.post("/admin/reload", tags=["admin"], summary="Re-ingest data/programs.json without crawling")
def reload_dataset(prune_directory: bool = False, key: dict = Depends(admin)):
    import json
    # two snapshots can exist: seed/ is baked into the image from git, data/ is the
    # mounted volume a sync writes. Take whichever is newer, so a redeploy is
    # picked up and a fresh sync is not silently ignored.
    seed = max((p for p in (ROOT / "seed" / "programs.json", ROOT / "data" / "programs.json")
                if p.exists()), key=lambda p: p.stat().st_mtime, default=None)
    if not seed:
        raise HTTPException(503, "no programs.json in data/ or seed/")
    # prune_directory deletes programs that only ever came from the disclose.io
    # directory and are absent from this snapshot, which is how a dedupe fix
    # removes the duplicate rows an earlier merge created. It cannot touch rows
    # that any other source contributed to.
    programs = json.load(open(seed, encoding="utf-8"))
    return envelope(store.ingest(
        programs, run_kind="reload",
        allow_removal=prune_directory,
        # a duplicate created by an earlier merge can carry the crawl source as
        # well, so both discovery sources are prunable; platform rows never are
        prune_only_sources=({"disclose-directory", "securitytxt"}
                            if prune_directory else None),
        prune_dotless_platform=prune_directory))


@app.post("/admin/ingest", tags=["admin"], summary="Ingest a dataset snapshot posted as JSON")
def ingest_snapshot(payload: dict, prune_directory: bool = False, key: dict = Depends(admin)):
    """Take the snapshot over HTTP instead of reading a file.

    The container builds its seed from git, and data/ is a docker volume, so a
    script on the host cannot assume either path is visible inside. Posting the
    snapshot removes that assumption.
    """
    programs = payload.get("programs") if isinstance(payload, dict) else payload
    if not isinstance(programs, list) or not programs:
        raise HTTPException(422, "expected {\"programs\": [...]}")
    return envelope(store.ingest(
        programs, run_kind="ingest",
        allow_removal=prune_directory,
        prune_only_sources=({"disclose-directory", "securitytxt"}
                            if prune_directory else None),
        prune_dotless_platform=prune_directory))


